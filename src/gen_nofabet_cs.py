#!/usr/bin/env python3
"""Generate NofabetG2p.cs and phonemes.txt from symbols/nofabet.yaml.

Run from anywhere:  python src/gen_nofabet_cs.py
The C# loads the exported .oudep's dict.txt and model.onnx, so the resource
must be the .oudep itself, copied in as G2p/Data/g2p-nofabet.zip.
"""
from pathlib import Path
import yaml

HERE = Path(__file__).resolve().parent
SYMBOLS = HERE / "symbols" / "nofabet.yaml"
OUT = HERE / "NofabetG2p.cs"
PHONES_TXT = HERE.parent / "phonemes.txt"

# Keep in sync with DiffSingerNorwegianPhonemizer.cs
VOWELS = "aa ae aeh aej aew ah aj ax ee eh ih ii oa oah oe oeh oej oh oj oo uh uu yh yy".split()
CONSONANTS = "b d f g h j k kj l lx m n ng nx p r rd rl rlx rn rnx rs rt s sj t v".split()

TEMPLATE = """using System;
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using Microsoft.ML.OnnxRuntime;
using Microsoft.ML.OnnxRuntime.Tensors;
using OpenUtau.Api;
using OpenUtau.Core.Util;

namespace DiffSingerNorwegian {
    // GENERATED by gen_nofabet_cs.py from configs/symbols/nofabet.yaml. Do not edit by hand.
    public class NofabetG2p : G2pPack {
__GRAPHEMES__

__PHONEMES__

__VOWELS__

        private const int EosId = 3;
        private const int FirstPhonemeId = 4; // ids 0-3 are <pad>, <unk>, <bos>, <eos>

        private static readonly object lockObj = new object();
        private static Dictionary<string, int> graphemeIndexes;
        private static IG2p dict;
        private static InferenceSession session;
        private static Dictionary<string, string[]> predCache = new Dictionary<string, string[]>();

        public NofabetG2p() {
            lock (lockObj) {
                if (graphemeIndexes == null) {
                    graphemeIndexes = graphemes
                        .Skip(FirstPhonemeId)
                        .Select((g, i) => Tuple.Create(g, i))
                        .ToDictionary(t => t.Item1, t => t.Item2 + FirstPhonemeId);
                    byte[] pack = File.ReadAllBytes(PackPath());
                    dict = BuildDictionary(pack);
                    session = new InferenceSession(Zip.ExtractBytes(pack, "model.onnx"));
                }
            }
            GraphemeIndexes = graphemeIndexes;
            Phonemes = phonemes;
            Dict = dict;
            Session = session;
            PredCache = predCache;
        }

        // The .oudep sits next to the DLL, in the Plugins folder.
        private static string PackPath() {
            string dir = Path.GetDirectoryName(typeof(NofabetG2p).Assembly.Location);
            return Path.Combine(dir, "g2p-nofabet.oudep");
        }

        // dict.txt lines are "word  p1 p2 ..." (two spaces), as written by export.py.
        private static IG2p BuildDictionary(byte[] pack) {
            var builder = G2pDictionary.NewBuilder();
            foreach (var p in phonemes.Skip(FirstPhonemeId)) {
                builder.AddSymbol(p, vowels.Contains(p));
            }
            foreach (var line in Zip.ExtractText(pack, "dict.txt")) {
                if (string.IsNullOrWhiteSpace(line) || line.StartsWith(";;;")) {
                    continue;
                }
                var parts = line.Trim().Split(new[] { "  " }, StringSplitOptions.None);
                if (parts.Length != 2) {
                    continue;
                }
                builder.AddEntry(
                    parts[0].ToLowerInvariant(),
                    parts[1].Split(' ', StringSplitOptions.RemoveEmptyEntries));
            }
            return builder.Build();
        }

        // The exported model is one graph: src in, fully decoded tgt out.
        // Replaces G2pPack.Predict, which expects the older stepwise interface.
        protected override string[] Predict(string grapheme) {
            Tensor<int> src = EncodeWord(grapheme);
            if (src.Length == 0 || Session == null) {
                return new string[0];
            }
            var inputs = new List<NamedOnnxValue> {
                NamedOnnxValue.CreateFromTensor("src", src),
            };
            using var outputs = Session.Run(inputs);
            Tensor<int> tgt = outputs.First().AsTensor<int>();
            var result = new List<string>();
            // Index 0 is BOS. Stop at EOS and skip any other special id.
            for (int i = 1; i < tgt.Dimensions[1]; i++) {
                int id = tgt[0, i];
                if (id == EosId) {
                    break;
                }
                if (id >= FirstPhonemeId && id < Phonemes.Length) {
                    result.Add(Phonemes[id]);
                }
            }
            return result.ToArray();
        }
    }
}
"""


def cs_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def cs_array(name: str, items: list[str]) -> str:
    body = "\n".join(f"            {cs_str(x)}," for x in items)
    return f"        private static readonly string[] {name} = new string[] {{\n{body}\n        }};"


def cs_set(name: str, items: list[str]) -> str:
    body = "\n".join(f"            {cs_str(x)}," for x in items)
    return f"        private static readonly HashSet<string> {name} = new HashSet<string> {{\n{body}\n        }};"


def main() -> None:
    sym = yaml.safe_load(SYMBOLS.read_text(encoding="utf8"))
    graphemes, phonemes = sym["graphemes"], sym["phonemes"]
    specials = ["<pad>", "<unk>", "<bos>", "<eos>"]

    assert graphemes[:4] == specials and phonemes[:4] == specials
    assert len(graphemes) == sym["num_graphemes"]
    assert len(phonemes) == sym["num_phonemes"]
    assert len(set(graphemes[4:])) == len(graphemes[4:]), "duplicate grapheme would break ToDictionary"

    typed = VOWELS + CONSONANTS
    assert len(typed) == len(set(typed)), "a phone is listed as both vowel and consonant"
    phone_set = set(phonemes[4:])
    assert set(typed) == phone_set, (
        f"missing: {phone_set - set(typed)}, extra: {set(typed) - phone_set}"
    )

    # Special ids are "" so every real id lines up with training.
    g = [""] * 4 + graphemes[4:]
    p = [""] * 4 + phonemes[4:]
    text = (
        TEMPLATE.replace("__GRAPHEMES__", cs_array("graphemes", g))
        .replace("__PHONEMES__", cs_array("phonemes", p))
        .replace("__VOWELS__", cs_set("vowels", VOWELS))
    )
    OUT.write_text(text, encoding="utf8")
    lines = [f"{p}\t{'vowel' if p in VOWELS else 'consonant'}" for p in phonemes[4:]]
    PHONES_TXT.write_text("\n".join(lines) + "\n", encoding="utf8")
    print(f"wrote {PHONES_TXT}")
    print(f"wrote {OUT} ({len(graphemes) - 4} graphemes, {len(phonemes) - 4} phonemes, {len(VOWELS)} vowels)")


if __name__ == "__main__":
    main()